export const notesRouter = createRouter({
  list: authedQuery.query(async ({ ctx }) => {
    const db = getDb();
    let userNotes = await db
      .select()
      .from(notes)
      .where(eq(notes.userId, ctx.user.id))
      .orderBy(desc(notes.updatedAt));

    // Auto-seed starter notes for new users
    if (userNotes.length === 0) {
      for (const starter of STARTER_NOTES) {
        await db.insert(notes).values({
          userId: ctx.user.id,
          title: starter.title,
          content: starter.content,
          tags: starter.tags,
        });
      }
      userNotes = await db
        .select()
        .from(notes)
        .where(eq(notes.userId, ctx.user.id))
        .orderBy(desc(notes.updatedAt));
    }

    return userNotes;
  }),

  get: authedQuery
    .input(z.object({ id: z.number() }))
    .query(async ({ ctx, input }) => {
      const db = getDb();
      const [note] = await db
        .select()
        .from(notes)
        .where(and(eq(notes.id, input.id), eq(notes.userId, ctx.user.id)));
      return note ?? null;
    }),

  create: authedQuery
    .input(
      z.object({
        title: z.string().min(1).max(500),
        content: z.string(),
        tags: z.array(z.string()).optional(),
        source: z.string().optional(),
      })
    )
    .mutation(async ({ ctx, input }) => {
      const db = getDb();
      const [note] = await db.insert(notes).values({
        userId: ctx.user.id,
        title: input.title,
        content: input.content,
        tags: input.tags ?? [],
        source: input.source ?? null,
      });
      return { id: Number(note.insertId) };
    }),

  update: authedQuery
    .input(
      z.object({
        id: z.number(),
        title: z.string().min(1).max(500).optional(),
        content: z.string().optional(),
        tags: z.array(z.string()).optional(),
        source: z.string().optional(),
      })
    )
    .mutation(async ({ ctx, input }) => {
      const db = getDb();
      const { id, ...updates } = input;
      await db
        .update(notes)
        .set(updates)
        .where(and(eq(notes.id, id), eq(notes.userId, ctx.user.id)));
      return { success: true };
    }),

  delete: authedQuery
    .input(z.object({ id: z.number() }))
    .mutation(async ({ ctx, input }) => {
      const db = getDb();
      await db
        .delete(notes)
        .where(and(eq(notes.id, input.id), eq(notes.userId, ctx.user.id)));
      return { success: true };
    }),

  deleteMany: authedQuery
    .input(z.object({ ids: z.array(z.number()) }))
    .mutation(async ({ ctx, input }) => {
      const db = getDb();
      for (const id of input.ids) {
        await db
          .delete(notes)
          .where(and(eq(notes.id, id), eq(notes.userId, ctx.user.id)));
      }
      return { success: true };
    }),

});
